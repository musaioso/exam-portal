function mulberry32(seed: number) {
  let a = seed >>> 0;
  return function () {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

function shuffle<T>(list: T[], random: () => number): T[] {
  const out = list.slice();
  for (let i = out.length - 1; i > 0; i--) {
    const j = Math.floor(random() * (i + 1));
    [out[i], out[j]] = [out[j], out[i]];
  }
  return out;
}

function stripPunct(w: string): string {
  return w.replace(/^[।,!?;:()«»"'`]+|[।,!?;:()«»"'`]+$/g, "").trim();
}

export function normalizeText(s: string): string {
  return String(s || "").trim().toLowerCase().normalize("NFC").replace(/\s+/g, " ");
}

export function buildProofreadingPassage(opts: {
  sentenceCount?: number;
  seed?: number;
  tag?: string | null;
}): ProofPassage {
  const rnd = mulberry32(opts.seed ?? (Date.now() & 0x7fffffff));
  const count = Math.max(2, Math.min(8, opts.sentenceCount ?? 5));

  const pool = opts.tag ? SENTENCES.filter((s) => s[2] === opts.tag) : SENTENCES;
  const picked = shuffle(pool.slice(), rnd).slice(0, Math.min(count, pool.length));

  // Inject a misspelling into each chosen sentence.
  const injected: { sentence: string; correct: string; wrong: string; tag: string; explanation: string }[] = [];
  for (const [correct, sentence, tag] of picked) {
    const item = SPELLING_BANK.find((b) => b.correct === correct);
    // Avoid trailing-hasanta variants in a passage: they render as a broken
    // glyph and read as a typo of the page, not of the word.
    const variants = item ? item.wrong.filter((w) => !w.endsWith("্") && w.trim() !== correct.trim()) : [];
    const pool = variants.length ? variants : item ? item.wrong : [correct];
    const wrong = pool[Math.floor(rnd() * pool.length)];
    const misspelled = sentence.replace(correct, wrong);
    injected.push({
      sentence: misspelled,
      correct,
      wrong,
      tag,
      explanation: TAG_NOTE[tag] || "",
    });
  }

  // Tokenize the whole passage, marking the injected misspellings.
  const tokens: ProofToken[] = [];
  let id = 0;
  for (const inj of injected) {
    const words = inj.sentence.split(/\s+/).filter(Boolean);
    for (const w of words) {
      const base = stripPunct(w);
      const isWrong = base === stripPunct(inj.wrong);
      tokens.push({
        id: id++,
        text: w,
        isWrong,
        correct: isWrong ? inj.correct : null,
        wrong: isWrong ? inj.wrong : null,
        explanation: isWrong ? inj.explanation : null,
        tag: isWrong ? inj.tag : null,
      });
    }
  }

  return {
    tokens,
    wrongCount: tokens.filter((t) => t.isWrong).length,
    seed: opts.seed ?? 0,
  };
}

