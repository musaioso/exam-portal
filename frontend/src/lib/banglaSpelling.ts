/**
 * Bangla spelling MCQ bank + generator.
 *
 * Why a curated bank instead of an algorithm or an AI call: spelling questions
 * are only useful when the key is definitely right. Mechanically swapping
 * ষ/শ/স or ই/ঈ can invent forms that are also real words, and a generated
 * "correct" answer that is subtly wrong teaches the mistake. Every entry below
 * therefore carries one hand-checked correct spelling plus three hand-written
 * misspellings, so generation is instant, offline and deterministic.
 *
 * A word becomes several different questions (the prompt quotes a different
 * misspelling each time), which keeps prompt-based duplicate detection useful
 * in the question bank without ever revealing the answer in the prompt.
 */

export type SpellingItem = {
  /** The one correct spelling. */
  correct: string;
  /** Three plausible misspellings (never real alternative spellings). */
  wrong: [string, string, string];
  /** Error family, used for the chapter/UI filter and the explanation. */
  tag: string;
};

export type GeneratedSpelling = {
  type: "mcq";
  difficulty: "easy" | "medium" | "hard";
  marks: number;
  prompt: string;
  options: string[];
  answer: string;
  explanation: string;
  /** Kept for the preview UI only; stripped before import. */
  tag: string;
};

