export const SPELLING_BANK: SpellingItem[] = RAW.map(([correct, w1, w2, w3, tag]) => ({
  correct,
  wrong: [w1, w2, w3],
  tag,
}));

export const SPELLING_BANK_SIZE = SPELLING_BANK.length;

/** Tag list in first-appearance order, for the filter dropdown. */
export const SPELLING_TAGS: string[] = SPELLING_BANK.reduce<string[]>((list, item) => {
  if (!list.includes(item.tag)) list.push(item.tag);
  return list;
}, []);

/** Small deterministic PRNG so a seed reproduces the same batch exactly. */
function mulberry32(seed: number) {
  let a = seed >>> 0;
  return function () {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

function shuffle<T>(list: T[], random: () => number): T[] {
  const out = list.slice();
  for (let i = out.length - 1; i > 0; i--) {
    const j = Math.floor(random() * (i + 1));
    [out[i], out[j]] = [out[j], out[i]];
  }
  return out;
}

const PROMPTS: ((wrong: string) => string)[] = [
  (wrong) => `‘${wrong}’ — শব্দটির শুদ্ধ বানান কোনটি?`,
  (wrong) => `‘${wrong}’ বানানটি ভুল। এর শুদ্ধ রূপ কোনটি?`,
  (wrong) => `বাক্যে ‘${wrong}’ শব্দটি ভুল বানানে লেখা। শুদ্ধ বানান কোনটি?`,
];

function difficultyOf(word: string): GeneratedSpelling["difficulty"] {
  const len = Array.from(word).length;
  if (len <= 4) return "easy";
  if (len >= 8) return "hard";
  return "medium";
}

/**
 * Build up to `count` fresh, non-repeating spelling questions.
 *
 * Every generated prompt is unique because it quotes the misspelling it asks
 * about, so the bank's prompt-based duplicate scan keeps working while the
 * question itself never gives the answer away. `exclude` lets the caller carry
 * already-produced/imported prompts across batches.
 */
export function buildSpellingQuestions(options: {
  count: number;
  seed?: number;
  exclude?: string[];
  tag?: string | null;
}): GeneratedSpelling[] {
  const { count, tag } = options;
  const random = mulberry32(options.seed ?? (Date.now() & 0x7fffffff));
  const exclude = new Set(options.exclude || []);

  type Candidate = { item: SpellingItem; shown: string; variant: number };
  const candidates: Candidate[] = [];
  for (const item of SPELLING_BANK) {
    if (tag && item.tag !== tag) continue;
    item.wrong.forEach((shown, variant) => candidates.push({ item, shown, variant }));
  }

  const out: GeneratedSpelling[] = [];
  const usedWords = new Set<string>();
  for (const cand of shuffle(candidates, random)) {
    if (out.length >= count) break;
    if (usedWords.has(cand.item.correct)) continue;

    const prompt = PROMPTS[cand.variant % PROMPTS.length](cand.shown);
    if (exclude.has(prompt)) continue;

    const options = shuffle([cand.item.correct, ...cand.item.wrong], random);
    const explanation = `শুদ্ধ বানান: ${cand.item.correct}। ${TAG_NOTE[cand.item.tag] || ""}`.trim();

    out.push({
      type: "mcq",
      difficulty: difficultyOf(cand.item.correct),
      marks: 1,
      prompt,
      options,
      answer: cand.item.correct,
      explanation,
      tag: cand.item.tag,
    });
    usedWords.add(cand.item.correct);
  }
  return out;
}
